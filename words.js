function parseWordBank(raw){
  const expanded=[],seen=new Set();
  for(const sourceLine of raw.split(/\n+/)){
    const line=sourceLine.replace(/\s+/g,' ').trim();
    if(!line) continue;
    const entries=line==='empresa abrigo nevera tal vez volver' ? line.split(' ') : line.split(/\s*\/\s*/);
    for(const entry of entries){
      const cleaned=entry.trim();
      const key=cleaned==='Mom'||cleaned==='mom'?`capitalization:${cleaned}`:cleaned.toLocaleLowerCase();
      if(cleaned&&!seen.has(key)){seen.add(key);expanded.push(cleaned);}
    }
  }
  return expanded;
}

